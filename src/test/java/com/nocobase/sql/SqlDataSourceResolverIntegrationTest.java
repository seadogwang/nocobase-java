    @Test
    @DisplayName("P0-B: Concurrent resolve of same key → only one external datasource created")
    void concurrentResolve_createsOnlyOneDatasource() throws Exception {
        // Use "reporting" datasource which is configured but not yet resolved
        int threadCount = 10;
        CountDownLatch startLatch = new CountDownLatch(1);
        ExecutorService executor = Executors.newFixedThreadPool(threadCount);

        List<Future<JdbcTemplate>> futures = new ArrayList<>();
        for (int i = 0; i < threadCount; i++) {
            futures.add(executor.submit(() -> {
                startLatch.await(); // all threads wait for the signal
                return resolver.resolve("reporting");
            }));
        }

        // Signal all threads to start concurrently
        startLatch.countDown();

        // Collect results — all must return the same JdbcTemplate instance
        JdbcTemplate first = futures.get(0).get(30, TimeUnit.SECONDS);
        assertNotNull(first, "First resolve should return a valid JdbcTemplate");

        for (int i = 1; i < threadCount; i++) {
            JdbcTemplate template = futures.get(i).get(30, TimeUnit.SECONDS);
            assertSame(first, template,
                    "All concurrent resolves must return the same JdbcTemplate instance");
        }

        executor.shutdown();
    }

