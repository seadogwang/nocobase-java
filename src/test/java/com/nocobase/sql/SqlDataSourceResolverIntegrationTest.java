    private Long memberUserId;
    private Long metricIdA, metricIdB, metricIdC;

    @BeforeAll
    void setUp() throws Exception {
        authAsAdmin();

        // ── Set up the analytics table using a direct JDBC connection ──
        // We use a direct connection (not the resolver) because the resolver
        // creates read-only datasources, and we need to CREATE TABLE / INSERT.
        try (Connection conn = DriverManager.getConnection(ANALYTICS_URL, "sa", "");
             Statement stmt = conn.createStatement()) {
            stmt.execute(
                    "CREATE TABLE IF NOT EXISTS \"" + ANALYTICS_TABLE + "\" (" +
                    "\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                    "\"metric_name\" VARCHAR(255) NOT NULL, " +
                    "\"metric_value\" DOUBLE NOT NULL, " +
                    "\"category\" VARCHAR(100), " +
                    "\"owner_id\" BIGINT" +
                    ")");
            stmt.execute("DELETE FROM \"" + ANALYTICS_TABLE + "\"");
            stmt.execute("INSERT INTO \"" + ANALYTICS_TABLE + "\" (\"metric_name\", \"metric_value\", \"category\", \"owner_id\") VALUES ('Page Views', 1500.0, 'traffic', 1)");
            stmt.execute("INSERT INTO \"" + ANALYTICS_TABLE + "\" (\"metric_name\", \"metric_value\", \"category\", \"owner_id\") VALUES ('Sessions', 320.0, 'traffic', 1)");
            stmt.execute("INSERT INTO \"" + ANALYTICS_TABLE + "\" (\"metric_name\", \"metric_value\", \"category\", \"owner_id\") VALUES ('Bounce Rate', 42.5, 'engagement', 2)");
        }

        // Capture generated IDs via the resolver (SELECT is allowed on read-only)
        JdbcTemplate analyticsJdbc = resolver.resolve("analytics");
        metricIdA = analyticsJdbc.queryForObject(
                "SELECT \"id\" FROM \"" + ANALYTICS_TABLE + "\" WHERE \"metric_name\" = ?", Long.class, "Page Views");
        metricIdB = analyticsJdbc.queryForObject(
                "SELECT \"id\" FROM \"" + ANALYTICS_TABLE + "\" WHERE \"metric_name\" = ?", Long.class, "Sessions");
        metricIdC = analyticsJdbc.queryForObject(
                "SELECT \"id\" FROM \"" + ANALYTICS_TABLE + "\" WHERE \"metric_name\" = ?", Long.class, "Bounce Rate");

        // ── Create SQL collection (no primary key) ──
        if (!runtimeService.exists(SQL_COLL)) {
            CollectionEntity sqlColl = new CollectionEntity(SQL_COLL, "Analytics Dashboard", "sql");
            sqlColl.setSql("SELECT \"id\", \"metric_name\", \"metric_value\", \"category\", \"owner_id\" FROM \"" + ANALYTICS_TABLE + "\"");
            sqlColl.setOptions("{\"dataSourceKey\": \"analytics\"}");
            ddlSynchronizer.createCollection(sqlColl, List.of(
                    new FieldEntity(SQL_COLL, "id", "bigInt"),
                    new FieldEntity(SQL_COLL, "metric_name", "string"),
                    new FieldEntity(SQL_COLL, "metric_value", "float"),
                    new FieldEntity(SQL_COLL, "category", "string"),
                    new FieldEntity(SQL_COLL, "owner_id", "bigInt")));
            runtimeService.reload(SQL_COLL);
        }

        // ── Create SQL collection with primary key ──
        if (!runtimeService.exists(SQL_COLL_PK)) {
            CollectionEntity sqlCollPk = new CollectionEntity(SQL_COLL_PK, "Analytics Dashboard PK", "sql");
            sqlCollPk.setSql("SELECT \"id\", \"metric_name\", \"metric_value\", \"category\", \"owner_id\" FROM \"" + ANALYTICS_TABLE + "\"");
            sqlCollPk.setOptions("{\"primaryKey\": \"id\", \"dataSourceKey\": \"analytics\"}");
            ddlSynchronizer.createCollection(sqlCollPk, List.of(
                    new FieldEntity(SQL_COLL_PK, "id", "bigInt"),
                    new FieldEntity(SQL_COLL_PK, "metric_name", "string"),
                    new FieldEntity(SQL_COLL_PK, "metric_value", "float"),
                    new FieldEntity(SQL_COLL_PK, "category", "string"),
                    new FieldEntity(SQL_COLL_PK, "owner_id", "bigInt")));
            runtimeService.reload(SQL_COLL_PK);
        }

        // ── Create member user for ACL tests ──
        String memberEmail = "ds_resolver_member@test.com";
        User member = userRepository.findByEmail(memberEmail).orElse(null);
        if (member != null) {
            memberUserId = member.getId();
        } else {
            member = new User();
            member.setEmail(memberEmail);
            member.setNickname("DS Resolver Member");
            member.setPassword("encoded");
            member = userRepository.save(member);
            memberUserId = member.getId();
        }

        // ── Ensure admin user exists for main DB tests ──
        // Tests like mainDbMetadataUnaffected and badJdbcUrl_sqlCollectionInvalid_mainSystemUnaffected
        // query the users table. The admin user should exist (created by TestDataInitializer),
        // but if the context is reused or tables are recreated, create it explicitly.
        // Use JdbcTemplate for direct insertion to ensure the row is visible to
        // DynamicRepository queries which use the same JdbcTemplate.
        userRepository.findByEmail("admin@nocobase.com").orElseGet(() -> {
            User admin = new User();
            admin.setEmail("admin@nocobase.com");
            admin.setNickname("Admin");
            admin.setPassword("encoded");
            return userRepository.save(admin);
        });
        // Also ensure at least one user row exists directly via JdbcTemplate
        // in case the JPA save is not yet visible to DynamicRepository's JdbcTemplate.
        Integer userCount = jdbcTemplate.queryForObject("SELECT COUNT(*) FROM \"users\"", Integer.class);
        if (userCount != null && userCount == 0) {
            jdbcTemplate.update("INSERT INTO \"users\" (\"email\", \"nickname\", \"password\") VALUES (?, ?, ?)",
                    "admin@nocobase.com", "Admin", "encoded");
        }

        Role memberRole = roleRepository.findByName("member").orElse(null);
        if (memberRole == null) fail("member role not found");
        boolean alreadyBound = userRoleRepository.findByUserId(memberUserId).stream()
                .anyMatch(ur -> ur.getRoleId().equals(memberRole.getId()));
        if (!alreadyBound) {
            UserRole ur = new UserRole();
            ur.setUserId(memberUserId);
            ur.setRoleId(memberRole.getId());
            userRoleRepository.save(ur);
        }
    }

    @AfterAll
    void tearDown() throws Exception {
        authAsAdmin();

        // Drop the analytics table using a direct connection
        try (Connection conn = DriverManager.getConnection(ANALYTICS_URL, "sa", "");
             Statement stmt = conn.createStatement()) {
            stmt.execute("DROP TABLE IF EXISTS \"" + ANALYTICS_TABLE + "\"");
        } catch (Exception e) {
            // ignore cleanup errors
        }

        // Clean up ACL permissions
        cleanupMemberPermissions(SQL_COLL);
        cleanupMemberPermissions(SQL_COLL_PK);

        // Delete SQL collection metadata from the database
        // so that the next test run doesn't try to load stale SQL collections
        try {
            collectionRepository.findByName(SQL_COLL).ifPresent(coll -> {
                fieldRepository.findByCollectionName(SQL_COLL).forEach(fieldRepository::delete);
                collectionRepository.delete(coll);
            });
            collectionRepository.findByName(SQL_COLL_PK).ifPresent(coll -> {
                fieldRepository.findByCollectionName(SQL_COLL_PK).forEach(fieldRepository::delete);
                collectionRepository.delete(coll);
            });
            // Also clean up the member user
            if (memberUserId != null) {
                userRoleRepository.findByUserId(memberUserId).forEach(userRoleRepository::delete);
                userRepository.deleteById(memberUserId);
            }
        } catch (Exception e) {
            // ignore cleanup errors
        }

        // Reload runtime to remove SQL collections
        runtimeService.reloadAll();
    }

